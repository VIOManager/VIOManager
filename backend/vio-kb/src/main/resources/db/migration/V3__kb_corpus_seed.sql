## 知识库是什么

知识库是团队的知识沉淀区，存放使用指南、技术分享、经验总结等文档。文档按分类组织（分类由管理员在字典里维护，如平台使用指南），支持按分类浏览和关键词搜索。

每篇文档带浏览数、收藏数、评论数。看到好文档可以收藏（进入我的收藏列表随时回看），可以在下方评论区讨论补充。评论支持可见性管理，不当评论会被管理员处理。

## 文档的三种形态

- 手册：直接在平台里书写正文的文档（如本系列平台使用指南），点开即读。
- 外链：收录的外部链接文档，平台存标题、摘要和链接，点击跳转原文。
- 附件：以文件形式上传的文档，平台保留原始文件名供下载。

还有一类特殊的 AI 提示词文档：内容是给 AI 用的提示词模板，带结构化定义。

## 发布与下架

文档由有权限的发布者创建：手册写正文、外链填地址，发布后全平台可见；也可以先存草稿慢慢写。文档支持置顶。已发布文档可以编辑更新（手册正文更新后知识索引同步重切），也可以下架——下架后不再可见，随时可重新上架。

## 与 AI 助手的联动

知识库是 AI 问答的弹药库：

- 文档发布、编辑、重新上架后，自动进入 AI 的知识范围（后台切片建索引，通常很快）。
- 文档下架或删除后，自动从 AI 的知识范围移出。
- 极端情况（如 AI 服务重启间隙漏了通知），管理员可以在管理端一键全量重建知识索引，把所有已发布文档补齐进 AI 的知识范围。

所以想让 AI 能回答的内容，先发到知识库里。

